function withoutSslParams(url: string): string {
  const parsed = new URL(url);
  parsed.searchParams.delete("sslmode");
  parsed.searchParams.delete("channel_binding");
  return parsed.toString();
}

function sqlitePlaceholders(text: string): string {
  return text.replace(/\$\d+/g, "?");
}

export function openSqlite(path: string): Sql {
  mkdirSync(dirname(path), { recursive: true });
  const db = new DatabaseSync(path);
  db.exec("PRAGMA foreign_keys = ON");
  db.exec(sqliteSchema);
  const columns = db.prepare("PRAGMA table_info(users)").all() as Array<{ name: string }>;
  if (!columns.some((column) => column.name === "lid")) {
    db.exec("ALTER TABLE users ADD COLUMN lid TEXT");
  }
  return {
    all: async <T>(text: string, params: unknown[] = []) =>
      db.prepare(sqlitePlaceholders(text)).all(...(params as never[])) as T[],
    get: async <T>(text: string, params: unknown[] = []) =>
      db.prepare(sqlitePlaceholders(text)).get(...(params as never[])) as T | undefined,
    run: async (text, params = []) => {
      db.prepare(sqlitePlaceholders(text)).run(...(params as never[]));
    },
  };
}

export async function openPostgres(url: string): Promise<Sql> {
  pg.types.setTypeParser(20, (value) => Number(value));
  const pool = new pg.Pool({
    connectionString: withoutSslParams(url),
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 60_000,
    idleTimeoutMillis: 60_000,
  });
  pool.on("error", (error) => {
    console.error(`[diza] Neon: ${error.message}`);
  });
  await pool.query("SELECT 1");
  for (const statement of postgresSchema) {
    await pool.query(statement);
  }
  const keepAlive = setInterval(() => {
    pool.query("SELECT 1").catch((error: Error) => {
      console.warn(`[diza] Neon adormeceu: ${error.message}`);
    });
  }, 240_000);
  keepAlive.unref();
  return {
    all: async (text, params = []) => (await pool.query(text, params)).rows,
    get: async (text, params = []) => (await pool.query(text, params)).rows[0],
    run: async (text, params = []) => {
      await pool.query(text, params);
    },
  };
}
